    for index in indexes:
        for record in read_csv(index):
            key = (
                record["dataset"],
                record["protocol"],
                record["model"],
                record["stress_config"],
                record["control_mode"],
                int(record["hidden_channels"]),
                int(record["num_layers"]),
            )
            grouped[key].append(record)
            source_paths[key].add(rel(index))
    lane_by_family_dataset = {}
