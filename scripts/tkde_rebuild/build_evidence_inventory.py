def load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def rel(path: Path | str) -> str:
    path = Path(path)
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def seeds_text(values: Iterable[int | str]) -> tuple[str, int]:
    seeds = sorted({int(value) for value in values})
    if not seeds:
        return "none", 0
    if seeds == list(range(seeds[0], seeds[-1] + 1)):
        return f"{seeds[0]}-{seeds[-1]}", len(seeds)
    return ";".join(str(seed) for seed in seeds), len(seeds)


def base_row(**updates: Any) -> dict[str, Any]:
    row: dict[str, Any] = {field: "" for field in FIELDS}
    row.update(updates)
    return row


def graph_visibility(protocol: str) -> str:
    return {
        "strict_inductive": "test nodes and incident test edges withheld from training graph; test-time graph restricted by strict contract",
        "inductive_isolated": "chronological split with isolated split-specific evaluation subgraph",
        "transductive": "full graph structure visible while test labels remain hidden",
        "late_window_holdout": "node history features use the first 60% of transactions (this protocol's training interval); test transaction labels unavailable",
        "early_to_late_transfer": "classifier labels use the first 50%, while the shared label-free node-history map uses the first 60% (including covariates from the first half of this protocol's validation interval); test labels unavailable",
    }.get(protocol, "defined by source experiment contract")


