from fraudshiftbench.io import parse_prediction_filename

POSITIVE_LABEL = 1
NEGATIVE_LABEL = 2


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def write_json(path: Path, payload: Mapping[str, Any]) -> None:
    ensure_dir(path.parent)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_csv(path: Path, rows: Sequence[Mapping[str, Any]], fields: Optional[Sequence[str]] = None) -> None:
    ensure_dir(path.parent)
    if fields is None:
        ordered: List[str] = []
        for row in rows:
            for key in row:
                if key not in ordered:
                    ordered.append(key)
        fields = ordered or ["status"]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(fields), extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def write_tex(path: Path, rows: Sequence[Mapping[str, Any]], columns: Sequence[str], caption: str) -> None:
    ensure_dir(path.parent)
    lines = [
        "% Auto-generated by FraudShiftBench CPU-only analyzers",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        f"\\caption{{{caption}}}",
        "\\begin{tabular}{" + "l" * len(columns) + "}",
        "\\toprule",
        " & ".join(c.replace("_", "\\_") for c in columns) + " \\\\",
        "\\midrule",
    ]
    for row in rows:
        values = []
        for col in columns:
            val = row.get(col, "")
            if isinstance(val, float):
                values.append(f"{val:.4f}")
            else:
                values.append(str(val).replace("_", "\\_"))
        lines.append(" & ".join(values) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    path.write_text("\n".join(lines), encoding="utf-8")


def markdown_table(rows: Sequence[Mapping[str, Any]], columns: Sequence[str]) -> str:
    if not rows:
        return "_No rows._"
    out = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    for row in rows:
        vals = []
        for col in columns:
            val = row.get(col, "")
            vals.append(f"{val:.4f}" if isinstance(val, float) else str(val))
        out.append("| " + " | ".join(vals) + " |")
    return "\n".join(out)


def prediction_files(root: Path, family: str) -> List[Path]:
    if family == "RB01":
        pred_dir = root / "results" / "runs_rb01" / "predictions"
    elif family == "RB02":
        pred_dir = root / "results" / "runs" / "predictions"
    else:
        raise ValueError(f"Unknown prediction family: {family}")
    return sorted(pred_dir.glob("*.csv")) if pred_dir.is_dir() else []


def load_prediction(path: Path, columns: Optional[Sequence[str]] = None) -> pd.DataFrame:
    if columns is None:
        return pd.read_csv(path)
    allowed = set(columns)
    return pd.read_csv(path, usecols=lambda c: c in allowed)


def prediction_metadata(path: Path, family: str) -> Dict[str, Any]:
    parsed = parse_prediction_filename(path)
    if parsed is None:
        raise ValueError(f"Cannot parse prediction filename: {path}")
    dataset, protocol, model, seed = parsed
    return {
        "artifact_family": family,
        "dataset": dataset,
        "protocol": protocol,
        "model": model,
        "seed": seed,
        "prediction_file": str(path),
    }


def family_prediction_index(root: Path, family: str) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for path in prediction_files(root, family):
        try:
            rows.append(prediction_metadata(path, family))
        except ValueError:
            continue
    return rows


def as_binary(labels: Sequence[int]) -> np.ndarray:
    return np.asarray([1 if int(y) == POSITIVE_LABEL else 0 for y in labels], dtype=int)


def confusion_counts(labels: Sequence[int], scores: Sequence[float], threshold: float = 0.5) -> Tuple[int, int, int, int]:
    y = as_binary(labels)
    s = np.asarray(scores, dtype=float)
    pred = (s >= threshold).astype(int)
    tp = int(((pred == 1) & (y == 1)).sum())
    fp = int(((pred == 1) & (y == 0)).sum())
    fn = int(((pred == 0) & (y == 1)).sum())
    tn = int(((pred == 0) & (y == 0)).sum())
    return tp, fp, fn, tn


def precision_recall_f1(labels: Sequence[int], scores: Sequence[float], threshold: float = 0.5) -> Dict[str, float]:
    tp, fp, fn, tn = confusion_counts(labels, scores, threshold)
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": float(tp),
        "fp": float(fp),
        "fn": float(fn),
        "tn": float(tn),
    }


def best_threshold(labels: Sequence[int], scores: Sequence[float], candidates: Optional[Sequence[float]] = None) -> Tuple[float, float]:
    if candidates is None:
        candidates = np.linspace(0.02, 0.98, 49)
    best_t = 0.5
    best_f1 = -1.0
    for t in candidates:
        f1 = precision_recall_f1(labels, scores, float(t))["f1"]
        if f1 > best_f1:
            best_t = float(t)
            best_f1 = float(f1)
    return best_t, best_f1


def rank_average_scores(scores_by_model: Mapping[str, Sequence[float]]) -> np.ndarray:
    keys = sorted(scores_by_model)
    if not keys:
        return np.asarray([], dtype=float)
    ranks = []
    for key in keys:
        s = np.asarray(scores_by_model[key], dtype=float)
        order = np.argsort(s, kind="mergesort")
        r = np.empty(len(s), dtype=float)
        r[order] = np.linspace(0.0, 1.0, len(s), endpoint=True)
        ranks.append(r)
    return np.mean(np.vstack(ranks), axis=0)


def brier_score(labels: Sequence[int], scores: Sequence[float]) -> float:
    y = as_binary(labels).astype(float)
    s = np.asarray(scores, dtype=float)
    return float(np.mean((s - y) ** 2)) if len(y) else 0.0


def ece_score(labels: Sequence[int], scores: Sequence[float], bins: int = 10) -> float:
    y = as_binary(labels).astype(float)
    s = np.asarray(scores, dtype=float)
    if len(y) == 0:
        return 0.0
    edges = np.linspace(0.0, 1.0, bins + 1)
    ece = 0.0
    for i in range(bins):
        lo = edges[i]
        hi = edges[i + 1]
        mask = (s >= lo) & (s <= hi if i == bins - 1 else s < hi)
        if not mask.any():
            continue
        ece += float(mask.mean()) * abs(float(s[mask].mean()) - float(y[mask].mean()))
    return float(ece)


def calibration_slope_intercept(labels: Sequence[int], scores: Sequence[float]) -> Tuple[float, float]:
    y = as_binary(labels).astype(float)
    s = np.clip(np.asarray(scores, dtype=float), 1e-6, 1 - 1e-6)
    if len(y) < 2 or np.std(s) <= 1e-12:
        return 0.0, float(y.mean()) if len(y) else 0.0
    logit = np.log(s / (1 - s))
    slope, intercept = np.polyfit(logit, y, deg=1)
    return float(slope), float(intercept)


def ks_distance(a: Sequence[float], b: Sequence[float]) -> float:
    x = np.sort(np.asarray(a, dtype=float))
    y = np.sort(np.asarray(b, dtype=float))
    if len(x) == 0 or len(y) == 0:
        return 0.0
    values = np.sort(np.unique(np.concatenate([x, y])))
    cdf_x = np.searchsorted(x, values, side="right") / len(x)
    cdf_y = np.searchsorted(y, values, side="right") / len(y)
    return float(np.max(np.abs(cdf_x - cdf_y)))


def rank_auc(labels: Sequence[int], scores: Sequence[float]) -> Optional[float]:
    y = np.asarray(labels, dtype=int)
    s = np.asarray(scores, dtype=float)
    keep = ~np.isnan(s)
    y = y[keep]
    s = s[keep]
    n_pos = int((y == 1).sum())
    n_neg = int((y == 0).sum())
    if n_pos == 0 or n_neg == 0:
        return None
    order = np.argsort(s, kind="mergesort")
    ranks = np.empty(len(s), dtype=float)
    sorted_scores = s[order]
    i = 0
    while i < len(s):
        j = i + 1
        while j < len(s) and sorted_scores[j] == sorted_scores[i]:
            j += 1
        ranks[order[i:j]] = (i + 1 + j) / 2.0
        i = j
    rank_sum_pos = float(ranks[y == 1].sum())
    return float((rank_sum_pos - n_pos * (n_pos + 1) / 2.0) / (n_pos * n_neg))


def normal_approx_pvalue(diffs: Sequence[float]) -> float:
    vals = np.asarray(diffs, dtype=float)
    vals = vals[~np.isnan(vals)]
    if len(vals) < 2:
        return 1.0
    sd = float(vals.std(ddof=1))
    if sd <= 1e-12:
        return 0.0 if abs(float(vals.mean())) > 1e-12 else 1.0
    z = float(vals.mean()) / (sd / math.sqrt(len(vals)))
    return float(math.erfc(abs(z) / math.sqrt(2.0)))


def correction_rows(rows: Sequence[Mapping[str, Any]], *, p_key: str = "p_value", alpha: float = 0.05) -> List[Dict[str, Any]]:
    out = [dict(row) for row in rows]
    indexed = sorted([(i, float(row.get(p_key, 1.0))) for i, row in enumerate(out)], key=lambda x: x[1])
    m = len(indexed)
    for rank, (idx, p) in enumerate(indexed, start=1):
        out[idx]["holm_threshold"] = alpha / max(1, m - rank + 1)
        out[idx]["survives_holm"] = bool(p <= out[idx]["holm_threshold"])
        out[idx]["bh_threshold"] = alpha * rank / max(1, m)
        out[idx]["survives_fdr"] = bool(p <= out[idx]["bh_threshold"])
    return out


def score_prior_adjust(scores: Sequence[float], source_prior: float, target_prior: float) -> np.ndarray:
    s = np.clip(np.asarray(scores, dtype=float), 1e-6, 1 - 1e-6)
    source_prior = min(max(float(source_prior), 1e-6), 1 - 1e-6)
    target_prior = min(max(float(target_prior), 1e-6), 1 - 1e-6)
    odds = s / (1 - s)
    factor = (target_prior / (1 - target_prior)) / (source_prior / (1 - source_prior))
    adj_odds = odds * factor
    return adj_odds / (1 + adj_odds)

